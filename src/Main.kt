/**
 * The main entry point for the application.
 */
fun main() {
    // Declare a constant value 'name' and assign it the string "Kotlin".
    val name = "Kotlin"
    
    // Print a greeting to the console, using string templating to include the name.
    println("Hello, $name!")

    // Loop through numbers from 1 to 5 (inclusive).
    for (i in 1..5) {
        // Inside the loop, print the current value of 'i'.
        println("i = $i")
    }
}